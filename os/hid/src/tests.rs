#[test]
fn qemu_mouse() {
    let p = parse(QEMU_MOUSE).expect("a mouse");
    assert!(!p.numbered);
    assert_eq!(p.buttons, Some((field(0, 0, 1, false, false), 5)));
    assert_eq!(p.x, Some(field(0, 8, 8, true, true)));
    assert_eq!(p.y, Some(field(0, 16, 8, true, true)));
    assert_eq!(p.wheel, Some(field(0, 24, 8, true, true)));
    assert_eq!(p.pan, None);
    // The left button held, 5 right, 3 up, the wheel a notch towards you.
    let report = [0x01, 5, (-3i8) as u8, (-1i8) as u8];
    assert_eq!(p.buttons_in(&report), Some(1));
    assert_eq!(p.x.unwrap().value(&report, false), Some(5));
    assert_eq!(p.y.unwrap().value(&report, false), Some(-3));
    assert_eq!(p.wheel.unwrap().value(&report, false), Some(-1));
    // A report cut short has no wheel.
    assert_eq!(p.wheel.unwrap().value(&report[..3], false), None);
}

#[test]
fn qemu_tablet() {
    let p = parse(QEMU_TABLET).expect("a pointing device");
    assert_eq!(p.buttons, Some((field(0, 0, 1, false, false), 3)));
    assert_eq!(p.x, Some(field(0, 8, 16, false, false)));
    assert_eq!(p.y, Some(field(0, 24, 16, false, false)));
    assert_eq!(p.wheel, Some(field(0, 40, 8, true, true)));
    let report = [0x04, 0xFF, 0x7F, 0x00, 0x40, 0x02];
    assert_eq!(p.buttons_in(&report), Some(4));
    assert_eq!(p.x.unwrap().value(&report, false), Some(32767));
    assert_eq!(p.y.unwrap().value(&report, false), Some(16384));
    assert_eq!(p.wheel.unwrap().value(&report, false), Some(2));
}

#[test]
fn receiver_mouse() {
    let p = parse(RECEIVER_MOUSE).expect("a mouse");
    assert!(p.numbered);
    assert_eq!(p.buttons, Some((field(2, 0, 1, false, false), 16)));
    assert_eq!(p.x, Some(field(2, 16, 12, true, true)));
    assert_eq!(p.y, Some(field(2, 28, 12, true, true)));
    assert_eq!(p.wheel, Some(field(2, 40, 8, true, true)));
    assert_eq!(p.pan, Some(field(2, 48, 8, true, true)));
    // X -5 (0xFFB) and Y 300 (0x12C), packed: 0xFB, 0xCF, 0x12.
    let report = [2, 0x00, 0x80, 0xFB, 0xCF, 0x12, 0x01, 0xFF];
    assert_eq!(p.buttons_in(&report), Some(1 << 15));
    assert_eq!(p.x.unwrap().value(&report, true), Some(-5));
    assert_eq!(p.y.unwrap().value(&report, true), Some(300));
    assert_eq!(p.wheel.unwrap().value(&report, true), Some(1));
    assert_eq!(p.pan.unwrap().value(&report, true), Some(-1));
    // Another report (the receiver's keyboard or volume keys, say) is none of these.
    let other = [3, 0x00, 0x80, 0xFB, 0xCF, 0x12, 0x01, 0xFF];
    assert_eq!(p.wheel.unwrap().value(&other, true), None);
    assert_eq!(p.buttons_in(&other), None);
}

#[test]
fn feature_reports_take_no_room_in_input_reports() {
    let p = parse(MULTIPLIER_MOUSE).expect("a mouse");
    assert!(p.numbered);
    assert_eq!(p.buttons, Some((field(0x11, 0, 1, false, false), 5)));
    assert_eq!(p.x, Some(field(0x11, 8, 16, true, true)));
    assert_eq!(p.y, Some(field(0x11, 24, 16, true, true)));
    assert_eq!(p.wheel, Some(field(0x11, 40, 8, true, true)));
    // AC Pan's page came just before it, after the wheel's: the wheel keeps its own.
    assert_eq!(p.pan, Some(field(0x11, 48, 8, true, true)));
}

#[test]
fn a_usage_declared_before_its_page_takes_that_page() {
    // X and Y declared while the page is still the buttons', then the generic desktop page: as Linux reads them.
    let d = [
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25,
        0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x03, 0x09, 0x30, 0x09, 0x31, 0x05, 0x01,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xC0, 0xC0,
    ];
    let p = parse(&d).expect("a mouse");
    assert_eq!(p.button_count(), 3);
    assert_eq!(p.x, Some(field(0, 8, 8, true, true)));
    assert_eq!(p.y, Some(field(0, 16, 8, true, true)));
}

#[test]
fn push_pop_whole_usages_and_long_items() {
    let d = [
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, // a mouse
        0x75, 0x08, 0x95, 0x01, 0x15, 0x81, 0x25, 0x7F, // bytes, one at a time, signed
        0xA4, // push
        0x05, 0x09, 0x19, 0x01, 0x29, 0x08, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, // 8 buttons
        0xB4, // pop: a signed byte again
        0x0B, 0x38, 0x00, 0x01, 0x00, 0x81, 0x06, // the wheel, as a whole 32-bit usage
        0xFE, 0x02, 0x00, 0xAA, 0xBB, // a long item, skipped
        0x0B, 0x30, 0x00, 0x01, 0x00, 0x81, 0x06, // X
        0xC0,
    ];
    let p = parse(&d).expect("a mouse");
    assert_eq!(p.buttons, Some((field(0, 0, 1, false, false), 8)));
    assert_eq!(p.wheel, Some(field(0, 8, 8, true, true)));
    assert_eq!(p.x, Some(field(0, 16, 8, true, true)));
}

