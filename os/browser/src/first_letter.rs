/// Whether a character is punctuation that goes with the first letter.
pub fn punctuation(c: char) -> bool {
    let c = c as u32;
    let (mut lo, mut hi) = (0, PUNCTUATION.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (a, b) = PUNCTUATION[mid];
        if c < a {
            hi = mid;
        } else if c > b {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    false
}

/// A mark that goes with the character before it (one of a letter's accents).
fn combining(c: char) -> bool {
    matches!(c as u32, 0x0300..=0x036F | 0x0483..=0x0489 | 0x0591..=0x05BD | 0x0610..=0x061A | 0x064B..=0x065F | 0x0E31 | 0x0E34..=0x0E3A | 0x0E47..=0x0E4E | 0x1AB0..=0x1AFF | 0x1DC0..=0x1DFF | 0x20D0..=0x20FF | 0x3099..=0x309A | 0xFE00..=0xFE0F | 0xFE20..=0xFE2F)
}

/// A space that comes before the first letter, or ends it (a line break, unless the text keeps its breaks).
fn space(c: char, keep_breaks: bool) -> bool {
    (matches!(c, ' ' | '\t' | '\n' | '\r' | '\x0C') && !(keep_breaks && c == '\n')) || c == '\u{A0}'
}

/// How much of a text (bytes) is its first letter: the spaces and punctuation before it, the letter (with its
/// accents), and the punctuation after it; 0 if there's none (the text ends, or a space comes, before a letter).
/// `keep_breaks`: the text keeps its line breaks (pre).
pub fn length(text: &str, keep_breaks: bool) -> usize {
    let chars: alloc::vec::Vec<(usize, char)> = text.char_indices().collect();
    let mut i = 0;
    while i < chars.len() && space(chars[i].1, keep_breaks) {
        i += 1;
    }
    let with_marks = |mut i: usize| {
        while i < chars.len() && combining(chars[i].1) {
            i += 1;
        }
        i
    };
    while i < chars.len() && punctuation(chars[i].1) {
        i = with_marks(i + 1);
    }
    // (Nothing before the line ends, or a space, or a kept line break ending the first line first: no first letter.)
    if i >= chars.len() || space(chars[i].1, keep_breaks) || chars[i].1 == '\n' {
        return 0;
    }
    i = with_marks(i + 1);
    while i < chars.len() && punctuation(chars[i].1) {
        i = with_marks(i + 1);
    }
    chars.get(i).map_or(text.len(), |&(at, _)| at)
}
